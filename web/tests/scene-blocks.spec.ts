  const navigation = dialog.getByRole("navigation", { name: "Navegação entre cenas" });
  await expect(navigation.getByRole("button")).toHaveCount(1);
  await expect(navigation.getByRole("button", { name: "Editar cena 1", exact: true })).toHaveAttribute("aria-current", "step");
